mot_src = os.path.join(SRC, 'mzboot.mot')
prg_file = os.path.join(OUT, 'gomz.prg')
r = subprocess.run([VASM6502, '-Fbin', '-o', prg_file, mot_src],
                   capture_output=True, text=True)
