sp5025_bin = os.path.join(OUT, 'sp5025.bin')
with open(sp5025_src, 'rb') as f:
    sp5025_data = f.read()
with open(sp5025_bin, 'wb') as f:
    f.write(sp5025_data)
print(f"SP-5025 BASIC: {len(sp5025_data)} bytes")

# Step 4: Assemble 6502 boot loader
